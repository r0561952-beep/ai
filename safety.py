"""Защита от сексуального контента с участием несовершеннолетних.

Используется:
  - при подготовке данных (prepare_rp.py): 18+ диалоги с любым признаком
    несовершеннолетнего выбрасываются целиком (строгий режим);
  - в чате (chat.py): если в карточке/сообщениях есть явный признак
    несовершеннолетнего и разговор сексуальный — модель не продолжает сцену.
"""
import re

_AGE = r"(?<![\d.,])(?:[1-9]|1[0-7])"  # отдельное число: «15 лет», но не «25 лет»

# Явные признаки (меньше ложных срабатываний) — для чата и для данных
STRONG = re.compile("|".join([
    r"несовершеннолет", r"малолет", r"\bлоли", r"\bшота\b", r"\bloli", r"\bshota",
    _AGE + r"\s?-?\s?(?:лет|летн\w*|годик\w*|годовал\w*)\b"
    r"(?!\s*(?:назад|спустя|тому|подряд|службы|работы|жизни|брака|отношений|в тюрьм))",
    r"\b(?:десяти|одиннадцати|двенадцати|тринадцати|четырнадцати|пятнадцати|шестнадцати|семнадцати)\s?-?\s?летн",
    r"\b" + _AGE + r"\s?(?:-?\s?years?[- ]old|yo\b|y/o)",
    r"школьни|первоклас|младшеклас|старшеклас|(?<![\d.,])(?:[1-9]|1[01])\s?-?\s?(?:й|м|ом|го)?\s?класс",
    r"подрост|тинейдж|\bteen|preteen|schoolgirl|schoolboy|underage|\bminor\b",
]), re.I)

# Косвенные признаки — только для строгой фильтрации обучающих 18+ данных
WEAK = re.compile("|".join([
    r"\bребён|\bребен|\bдетск|\bдетей\b|\bдети\b|\bмладен|\bchild|\bkids?\b",
    r"\bдевочк|\bмальчик|\bмальчишк|\bдевчушк",
    r"\bдочь\b|\bдочк|\bдочер|\bсынок|\bсынишк",
]), re.I)

SEXUAL = re.compile("|".join([
    r"\bсекс", r"трах", r"\bеб[аул]", r"выеб", r"\bчлен(?:а|ом|у)?\b", r"пенис", r"вагин", r"клитор",
    r"оргазм", r"минет", r"\bконч(?:и|а|у|ил)", r"сперм", r"эрекц", r"возбужд", r"голая|голый|голые",
    r"обнаж[её]н", r"раздева", r"\bгруд(?:ь|и|ью)\b", r"\bсоск", r"интим", r"похот", r"\bsex", r"\bnude",
]), re.I)

REFUSAL = "⛔ Сексуальные сцены с участием несовершеннолетних я не отыгрываю. Давай сменим сцену."


def mentions_minor(text, strict=False):
    """strict=True — ловить и косвенные признаки (для чистки 18+ данных)."""
    return bool(STRONG.search(text) or (strict and WEAK.search(text)))


def is_sexual(text):
    return bool(SEXUAL.search(text))


def blocked(context, reply=""):
    """True, если сцена сексуальная и в ней явно есть несовершеннолетний."""
    return mentions_minor(context + "\n" + reply) and is_sexual(context + "\n" + reply)
